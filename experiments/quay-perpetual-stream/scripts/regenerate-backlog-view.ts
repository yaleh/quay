#!/usr/bin/env node
// regenerate-backlog-view.ts — M24-task-backlog-projection-impl Stage 4.1 (DIR-015 item 2 /
// m13 design doc §13). Regenerates `backlog.md` as a GENERATED VIEW over the task store's
// `label: milestone-candidate` tasks, instead of hand-edited canonical prose.
//
// Per §13's two explicit ordering decisions:
//   - Default order is VALUE-ordered (not recency): DONE/STALE tasks are grouped separately from
//     open (todo/ready) candidates; open candidates are listed grouped by value type, with the
//     `## Value type / cadence` body field surfaced verbatim (no new priority field invented).
//   - Recency is available as an explicit ALTERNATE view (`--sort=updated`), never primary.
//
// Usage:
//   node regenerate-backlog-view.ts <tasks-json-file> [--sort=value|updated] [--out=<path>]
//
//   <tasks-json-file>   a `task_list --label milestone-candidate --json` payload (array of tasks)
//   --sort=value        default: DONE/STALE first (grouped), then open candidates grouped by
//                        value-type/cadence text, id alphabetical within each group.
//   --sort=updated       alternate: all tasks (DONE/STALE and open alike) ordered by `updatedAt`
//                        descending (most-recently-touched first) — explicitly labeled as the
//                        secondary/alternate view in the generated output, never presented as the
//                        default.
//   --out=<path>        write to this path instead of stdout (default: stdout).
//
// This script is READ-ONLY with respect to the task store — it only reads the supplied JSON and
// writes the regenerated markdown file. It does not call task_write.

import fs from "node:fs";
import { extractSection } from "./task-schema.ts";

// extractSection is imported from task-schema.mjs (the single canonical definition per ADR-004).
// The canonical function returns null when the section is not found and untrimmed text when found.
// Call sites use `|| fallback` (handles both null and undefined) and apply .trim() where needed.

interface Task {
  id: string;
  title: string;
  status: string;
  labels?: string[];
  body?: string;
  updatedAt?: number;
}

interface Flags {
  sort?: string;
  out?: string;
  [key: string]: string | boolean | undefined;
}

const args = process.argv.slice(2);
const positional = args.filter((a) => !a.startsWith("--"));
const flags: Flags = Object.fromEntries(
  args
    .filter((a) => a.startsWith("--"))
    .map((a) => {
      const [k, v] = a.slice(2).split("=");
      return [k, v === undefined ? true : v];
    })
);

if (positional.length < 1) {
  console.error("Usage: node regenerate-backlog-view.ts <tasks-json-file> [--sort=value|updated] [--out=<path>]");
  process.exit(2);
}

const tasksJsonPath = positional[0];
const sortMode: string = (flags.sort as string) || "value";
const outPath: string | undefined = flags.out as string | undefined;

let tasks: Task[];
try {
  tasks = JSON.parse(fs.readFileSync(tasksJsonPath, "utf8"));
} catch (e: any) {
  console.error("ERROR: could not parse tasks JSON: " + e.message);
  process.exit(2);
}
if (!Array.isArray(tasks)) tasks = [tasks];

function isDoneOrStale(t: Task): boolean {
  return t.status === "done" || (t.labels || []).includes("stale");
}

function fmtRow(t: Task): string {
  // extractSection returns null when not found; null ?? fallback handles it. .trim() strips the
  // leading newline the canonical (depth-aware) implementation includes before the section body.
  const valueType = (extractSection(t.body, "Value type / cadence") ?? "").trim() || "(unspecified)";
  const source = (extractSection(t.body, "Source") ?? "").trim() || "(unspecified)";
  const outcome = (
    (extractSection(t.body, "Outcome \\(verbatim from backlog\\.md DONE column.*?\\)") ??
     extractSection(t.body, "Outcome") ??
     extractSection(t.body, "Status mirror") ??
     "(no outcome/status-mirror text found)")
  ).trim();
  const notSelectedRaw = extractSection(t.body, "Not selected \\(.*?\\)");
  const notSelected = notSelectedRaw !== null ? notSelectedRaw.trim() : null;
  const milestoneLabel = (t.labels || []).find((l) => l.startsWith("milestone:"));
  let line = `| ${t.id} | ${t.title} | ${source} | ${valueType} | ${t.status}${milestoneLabel ? ` (${milestoneLabel})` : ""} | ${outcome.replace(/\n/g, " ")} |`;
  if (notSelected) {
    line += ` _Not-selected note: ${notSelected.replace(/\n/g, " ")}_`;
  }
  return line;
}

const header = `# Milestone / Opportunity Backlog — quay-perpetual-stream (Experiment 5)

**GENERATED VIEW — do not hand-edit.** Regenerated by \`scripts/regenerate-backlog-view.ts\` from
the task store's \`label: milestone-candidate\` tasks (M24-task-backlog-projection-impl, DIR-015
item 2 / m13 design doc §13). The task store is canonical; this file is a value-ordered projection
of it, with an explicit recency alternate available via \`--sort=updated\` (never the default order,
per §13's own ordering decision — recency actively misorders SELECT candidates).

Regenerated at: ${new Date().toISOString()}
Sort mode: **${sortMode}**${sortMode === "updated" ? " (ALTERNATE view — recency-ordered, not the value-ordered default)" : " (default — value-ordered, not recency)"}
Source: ${tasksJsonPath}
`;

let body = "";

if (sortMode === "updated") {
  const sorted = [...tasks].sort((a, b) => (b.updatedAt || 0) - (a.updatedAt || 0));
  body += "\n## All candidates, most-recently-updated first (alternate view)\n\n";
  body += "| id | title | source | value type / cadence | status | outcome / status-mirror |\n";
  body += "|---|---|---|---|---|---|\n";
  for (const t of sorted) body += fmtRow(t) + "\n";
} else {
  const done = tasks.filter(isDoneOrStale).sort((a, b) => a.id.localeCompare(b.id));
  const open = tasks.filter((t) => !isDoneOrStale(t)).sort((a, b) => a.id.localeCompare(b.id));

  body += "\n## Open candidates (value-ordered — not yet DONE/STALE)\n\n";
  body += "| id | title | source | value type / cadence | status | outcome / status-mirror |\n";
  body += "|---|---|---|---|---|---|\n";
  for (const t of open) body += fmtRow(t) + "\n";

  body += "\n## DONE / STALE (closed — backfilled + executed)\n\n";
  body += "| id | title | source | value type / cadence | status | outcome / status-mirror |\n";
  body += "|---|---|---|---|---|---|\n";
  for (const t of done) body += fmtRow(t) + "\n";
}

const out = header + body;

if (outPath) {
  fs.writeFileSync(outPath, out, "utf8");
  console.log(`Wrote ${out.length} bytes to ${outPath} (${tasks.length} tasks, sort=${sortMode})`);
} else {
  process.stdout.write(out);
}
