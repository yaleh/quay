#!/usr/bin/env node
// extension-point-criteria.ts — generate the "extension-point criteria four-piece set" AC/DoD
// skeleton for a refactor slice (DIR-133 裁定 2 ; tasks/gap-extension-point-refactor-criteria-scaffold).
//
// WHY THIS EXISTS: the four-arm criterion set (正臂 / 负臂 / 注入泄漏 / 红线基线) is the same shape on
// every slice, yet it was hand-copied on every refactor (claudecodeui 2026-10-22: five slices, five
// hand-written sets). Copying it by hand is where the vacuous forms creep in — most often a positive
// arm written as "handler 存在" (an existence check, not the required `triggered=1` COUNT) and a
// negative arm shipped ALONE (green for the wrong reason when the wiring is broken).
//
// THIS SCRIPT ONLY PRINTS (dry-run): it never writes a task file. The task body goes through the
// Provider ABI (`task_write`) — the scaffold's stdout is pasted into `## Acceptance Criteria`.
// `--task-id` is echoed into the skeleton for traceability; the script does not read the store.
//
// The emitted text is the SINGLE template the checker (`extension-point-criteria-check.ts`) judges:
//   正臂      → `triggered=1` count assertion (the liveness check; no separate one)
//   负臂      → `triggered=0` when unregistered, and it is INVALID without the counted positive arm
//   注入泄漏  → a leaking dispatcher makes the SAME assertions red (proves the negative arm is not vacuous)
//   红线基线  → `wc -l <centre>` red BEFORE the change — a single-shot AC, NOT a standing ratchet
//
// Exit codes: 0 = scaffold printed; 1 = never used for a content verdict; 2 = usage / environment error.
//
// Run:
//   node --experimental-strip-types plugin/scripts/extension-point-criteria.ts \
//     --scaffold --task-id <id> --central <file> --outside <module>
//   node --experimental-strip-types plugin/scripts/extension-point-criteria.ts --help

import { helpExit, isDirectEntry, flagValue } from "./gate-script-base.ts";

const USAGE = `extension-point-criteria.ts — print the extension-point four-arm AC/DoD skeleton (dry-run; never writes)
usage: extension-point-criteria.ts --scaffold --task-id <id> --central <file> --outside <module>
  --central  the CENTRE file the slice is extracting from (e.g. packages/quay/src/serve.ts)
  --outside  the extension point new code should land in (e.g. a handler registry module)
exit 0 = scaffold printed | 2 = usage / environment error`;

/** The fixed sentence AC2 requires verbatim in the scaffold output. */
export const SINGLE_SHOT_NOTE =
  "本 AC 是单次验收、非常设棘轮：红线基线只在本次重构任务验收时由 worker 检查一次，任务 done 后永不复评，" +
  "不进入常设检查链，也不需要重锚规则。常设棘轮属于设计演进读数例程（design-evolution-readings.ts）的领域，本 AC 不假装拥有它。";

/** The positive arm's required COUNT form, exported so the test and template share one spelling. */
export const POSITIVE_COUNT_FORM = "triggered=1";

/**
 * Build the scaffold text. Pure (used by the test), so the CLI and the assertion read the same bytes.
 */
export function buildScaffold(opts: { taskId: string; central: string; outside: string }): string {
  const { taskId, central, outside } = opts;
  return `<!-- extension-point-criteria scaffold — generated by plugin/scripts/extension-point-criteria.ts -->
<!-- task: ${taskId} ; central: ${central} ; outside: ${outside} -->
<!-- dry-run: paste the AC block below into the task's ## Acceptance Criteria through Provider ABI task_write. -->

## Acceptance Criteria

<!-- 扩展点判据四件套 — paste these four items into the task's own Acceptance Criteria via task_write. -->

- [ ] 正臂（活性检查）：从 ${outside} 注册一个新的处理单元、不改 ${central}，运行后读数必须是 ${POSITIVE_COUNT_FORM}（计数断言，不是「handler 存在」）。取假方式：删掉/断线 ${outside} 的注册后同一断言读数为 triggered=0 ⇒ 本条必红。**这条正臂就是活性检查，不另配。**
- [ ] 负臂：同一个断言在【未注册】时读数为 triggered=0。取假方式：分派器泄漏/无条件触发时该断言必红。⚠️ 负臂必须与一条 counted 正臂（${POSITIVE_COUNT_FORM}）成对；**只写负臂、不写正臂 ⇒ 判据无效**，检查器判 missing-arms。
- [ ] 注入泄漏：把 ${central} 的分派器替换成泄漏实现（无视注册表、无条件调用），上一臂/正臂的同一断言必须打红。取假方式：替换后仍绿 ⇒ 该臂没测到分派器。它的作用是证明【负臂断言本身不真空】，不是给正臂兜底。
- [ ] 红线基线：改动前记录 \`wc -l ${central}\` 的基线（<填基线行数>），并断言改动后的中心文件行数 < 基线；在改动前跑该断言必须为红。取假方式：基线前跑不红 ⇒ 断言没测到那次增长。**本 AC 是单次验收、非常设棘轮**，不是常设检查。

### 固定说明

${SINGLE_SHOT_NOTE}

### 落 AC 前自检

\`\`\`bash
node --experimental-strip-types plugin/scripts/extension-point-criteria-check.ts --task-id ${taskId} --json
\`\`\`

四态读法：satisfied（四臂齐备）/ missing-arms（逐臂具名缺哪几臂）/ not-applicable（不是设计切片）/ NOT-EVALUATED（AC 段读不到，独立取值，不得与 satisfied 同形）。
`;
}

function main(): number {
  const argv = process.argv.slice(2);
  if (argv.includes("--help") || argv.includes("-h")) helpExit(USAGE);
  if (!argv.includes("--scaffold")) {
    process.stderr.write(`ERROR: --scaffold is required\n${USAGE}\n`);
    return 2;
  }
  const taskId = flagValue(argv, "--task-id");
  const central = flagValue(argv, "--central");
  const outside = flagValue(argv, "--outside");
  const missing = [
    ["--task-id", taskId],
    ["--central", central],
    ["--outside", outside],
  ].filter(([, v]) => v === undefined || v === "");
  if (missing.length > 0) {
    process.stderr.write(`ERROR: missing required flag(s): ${missing.map(([n]) => n).join(", ")}\n${USAGE}\n`);
    return 2;
  }
  process.stdout.write(buildScaffold({ taskId: String(taskId), central: String(central), outside: String(outside) }));
  return 0;
}

if (isDirectEntry(import.meta, process.argv[1], "extension-point-criteria")) {
  process.exit(main());
}
